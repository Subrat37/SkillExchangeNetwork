package org.example.skillexchangenetwork.entity;

import jakarta.persistence.*;
import lombok.*;

@Entity
@Table(name = "Skills")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class Skill {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false, unique = true)
    private String name;

    private String description;
}
